CREATE OR REPLACE FUNCTION public.fn_restore_stock_on_waste_delete()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_current_stock NUMERIC;
    v_clean_batch BIGINT;
    v_clean_qty NUMERIC;
BEGIN
    v_clean_batch := OLD.batch_id;
    v_clean_qty := ABS(COALESCE(OLD.quantity, 0));

    UPDATE public.products
    SET quantity = COALESCE(quantity, 0) + v_clean_qty
    WHERE id = OLD.product_id
    RETURNING quantity INTO v_current_stock;

    INSERT INTO public.inventory_movements (
        batch_id, product_id, product_name, change_amount,
        previous_quantity, new_quantity, operation_type, reason, notes, created_at, "user", is_synced
    ) VALUES (
        v_clean_batch, OLD.product_id, OLD.product_name, v_clean_qty,
        (v_current_stock - v_clean_qty), v_current_stock,
        'ENTRADA', 'Anulación Gasto/Merma', 'Sistema BD: Restauración automática.', NOW(), 'Sistema', 0
    );

    IF v_clean_batch IS NOT NULL THEN
        UPDATE public.batches
        SET quantity = COALESCE(quantity, 0) + v_clean_qty
        WHERE id = v_clean_batch;
    END IF;

    RETURN OLD;
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_sanitize_product_codes()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
    -- Si el código de barras está vacío o solo contiene espacios, mutarlo a NULL
    IF TRIM(NEW.barcode) = '' THEN
        NEW.barcode := NULL;
    END IF;

    -- Si el código interno (SKU) está vacío, mutarlo a NULL
    IF TRIM(NEW.code) = '' THEN
        NEW.code := NULL;
    END IF;

    -- Opcional (Recomendado): Forzar el nombre a mayúsculas y quitar espacios en blanco
    -- para mantener consistencia visual y geométrica en las búsquedas
    IF NEW.name IS NOT NULL THEN
        NEW.name := UPPER(TRIM(NEW.name));
    END IF;

    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_soft_delete_batch(p_batch_id text, p_user_name text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_product_id bigint;
    v_product_name text;
    v_quantity numeric;
BEGIN
    SELECT product_id, quantity INTO v_product_id, v_quantity 
    FROM public.batches WHERE id = p_batch_id::bigint;
    
    IF NOT FOUND THEN RETURN; END IF;
    SELECT name INTO v_product_name FROM public.products WHERE id = v_product_id;

    -- Borrado lógico y recálculo matemático
    UPDATE public.batches SET is_active = 0, quantity = 0 WHERE id = p_batch_id::bigint;
    
    UPDATE public.products SET quantity = (
        SELECT COALESCE(SUM(quantity), 0) FROM public.batches WHERE product_id = v_product_id AND is_active = 1
    ) WHERE id = v_product_id;

    -- Historial
    INSERT INTO public.inventory_movements (
        batch_id, product_id, product_name, change_amount, previous_quantity, new_quantity, 
        operation_type, reason, "user", created_at, is_synced
    ) VALUES (
        p_batch_id::bigint, v_product_id, v_product_name, -v_quantity, v_quantity, 0, 
        'AJUSTE', 'Retiro de Lote (Soft Delete)', p_user_name, NOW(), '1'
    );
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_soft_delete_product(p_product_id text, p_user_name text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_product_name text;
    v_total_qty numeric;
BEGIN
    -- Validar existencia convirtiendo el texto a ID internamente
    SELECT name, quantity INTO v_product_name, v_total_qty 
    FROM public.products 
    WHERE id = p_product_id::bigint;

    IF NOT FOUND THEN 
        RAISE EXCEPTION 'Producto ID % no encontrado.', p_product_id;
    END IF;

    -- Borrado lógico
    UPDATE public.products 
    SET is_active = '0', quantity = 0 
    WHERE id = p_product_id::bigint;

    UPDATE public.batches 
    SET is_active = 0, quantity = 0 
    WHERE product_id = p_product_id::bigint;

    -- Trazabilidad
    IF v_total_qty > 0 THEN
        INSERT INTO public.inventory_movements (
            product_id, product_name, change_amount, previous_quantity, new_quantity, 
            operation_type, reason, "user", created_at, is_synced
        ) VALUES (
            p_product_id::bigint, v_product_name, -v_total_qty, v_total_qty, 0, 
            'AJUSTE', 'Eliminación del sistema (Soft Delete)', p_user_name, NOW(), '1'
        );
    END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_sync_all_sequences()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_table RECORD;
    v_seq TEXT;
    v_max_id BIGINT;
BEGIN
    -- Iterar sobre todas las tablas del esquema 'public'
    FOR v_table IN 
        SELECT table_name 
        FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
    LOOP
        -- Buscar si la tabla tiene una secuencia atada a la columna 'id'
        v_seq := pg_get_serial_sequence('public.' || v_table.table_name, 'id');
        
        IF v_seq IS NOT NULL THEN
            -- Obtener el ID máximo actual de la tabla
            EXECUTE format('SELECT COALESCE(MAX(id), 0) FROM public.%I', v_table.table_name) INTO v_max_id;
            
            -- Sincronizar la secuencia estrictamente con el ID máximo
            IF v_max_id > 0 THEN
                EXECUTE format('SELECT setval(%L, %s)', v_seq, v_max_id);
            END IF;
        END IF;
    END LOOP;
END;
$function$;

