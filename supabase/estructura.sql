CREATE VIEW public."reporte_utilidad_hoy" AS
WITH detalleventas AS (
         SELECT sd.product_id,
            sd.product_name AS producto,
            sum(sd.quantity) AS cantidad_vendida,
            COALESCE(max(sd.cost_at_moment), max(p.cost_price), 0::numeric) AS costo_unitario,
            sum(sd.subtotal) AS ingresos_totales
           FROM public.sale_details sd
             JOIN public.sales s ON sd.sale_id = s.id
             JOIN public.products p ON sd.product_id = p.id
          WHERE s.created_at::date = CURRENT_DATE AND s.sunat_status <> 'ANULADO'::text
          GROUP BY sd.product_id, sd.product_name
        ), calculobruto AS (
         SELECT COALESCE(sum(detalleventas.ingresos_totales), 0::numeric) AS ingresos_totales,
            COALESCE(sum(detalleventas.cantidad_vendida * detalleventas.costo_unitario), 0::numeric) AS costo_total_mercaderia
           FROM detalleventas
        ), totalmermas AS (
         SELECT COALESCE(sum(waste.total_loss), 0::double precision) AS mermas_hoy
           FROM public.waste
          WHERE waste.created_at::date = CURRENT_DATE
        )
 SELECT CURRENT_DATE AS fecha,
    cb.ingresos_totales AS "Ingreso Bruto",
    cb.costo_total_mercaderia AS "Costo Inversión",
    tm.mermas_hoy AS "Pérdida Mermas",
    (cb.ingresos_totales - cb.costo_total_mercaderia)::double precision - tm.mermas_hoy AS "UTILIDAD NETA REAL"
   FROM calculobruto cb,
    totalmermas tm;

CREATE VIEW public."reporte_utilidades" AS
SELECT s.id AS sale_id,
    s.created_at,
    s.total AS ingreso_total,
    s.sunat_status,
    COALESCE(sum(d.quantity * d.cost_at_moment), 0::numeric) AS costo_total_venta,
    s.total - COALESCE(sum(d.quantity * d.cost_at_moment), 0::numeric)::double precision AS utilidad_bruta
   FROM public.sales s
     LEFT JOIN public.sale_details d ON s.id = d.sale_id
  WHERE s.sunat_status <> 'ANULADO'::text
  GROUP BY s.id, s.created_at, s.total, s.sunat_status;

