CREATE OR REPLACE FUNCTION public.trg_sync_product_name()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
    IF NEW.name <> OLD.name THEN
        -- Se elimina la actualización a "batches" porque esa tabla no almacena el nombre.
        UPDATE public.inventory_movements SET product_name = NEW.name WHERE product_id = NEW.id;
        UPDATE public.waste SET product_name = NEW.name WHERE product_id = NEW.id;
    END IF;
    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_fiado_status()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_fiado_id BIGINT;
    v_total_paid NUMERIC;
    v_amount NUMERIC;
BEGIN
    -- 1. Extraemos el identificador de la cuenta con seguridad
    v_fiado_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.fiado_id ELSE NEW.fiado_id END;

    -- 2. PROTECCIÓN CONTRA NULOS: Si el pago no está enlazado a un crédito específico, cancelamos la mutación 
    -- y dejamos que el pago entre a la caja sin romper el sistema de fiados.
    IF v_fiado_id IS NULL THEN
        RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
    END IF;

    -- 3. Calcular la liquidez real inyectada
    SELECT COALESCE(SUM(amount), 0) INTO v_total_paid
    FROM public.debt_payments
    WHERE fiado_id = v_fiado_id;

    -- 4. Extraer el valor total matriz de la deuda
    SELECT amount INTO v_amount
    FROM public.fiados
    WHERE id = v_fiado_id;

    -- 5. Lógica de Mutación Matemática
    IF v_amount IS NOT NULL THEN
        UPDATE public.fiados
        SET 
            paid_amount = v_total_paid,
            status = CASE 
                WHEN v_total_paid >= (v_amount - 0.05) THEN 'CANCELADO'
                ELSE 'PENDIENTE'
            END,
            date_paid = CASE 
                WHEN v_total_paid >= (v_amount - 0.05) THEN NOW()::text
                ELSE NULL
            END
        WHERE id = v_fiado_id;
    END IF;

    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_stock_from_waste()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
    UPDATE public.products
    SET quantity = quantity + NEW.quantity
    WHERE id = NEW.product_id;
    RETURN NEW;
END;
$function$;

